const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { chromium } = require('playwright');
const { getConfig } = require('../src/config');
const { createPool } = require('../src/db');
const { createApp } = require('../src/app');
const { initialize } = require('./init-db');
const { seed } = require('./seed');

async function main() {
  const config = getConfig();
  if (!process.env.TEST_DB_USER || !process.env.TEST_DB_PASSWORD) throw new Error('Cần TEST_DB_USER và TEST_DB_PASSWORD để tạo database QA riêng.');
  const database = `quiz_browser_${Date.now()}_${crypto.randomBytes(3).toString('hex')}`;
  const dbConfig = {...config.db,database,user:process.env.TEST_DB_USER,password:process.env.TEST_DB_PASSWORD};
  await initialize(dbConfig);
  const pool = createPool(dbConfig);
  const credentials = {SEED_ADMIN_EMAIL:'admin@browser.local',SEED_ADMIN_PASSWORD:'Browser-Admin!654',SEED_STUDENT_EMAIL:'student@browser.local',SEED_STUDENT_PASSWORD:'Browser-Student!654'};
  let server, browser;
  try {
    await seed(pool, credentials);
    server = createApp({pool,config:{...config,secure:false}}).listen(0,'127.0.0.1');
    await new Promise(resolve=>server.once('listening',resolve));
    const base = `http://127.0.0.1:${server.address().port}`;
    browser = await chromium.launch({channel:process.env.BROWSER_CHANNEL || 'chrome',headless:true});
    const context = await browser.newContext({viewport:{width:1440,height:1000}});
    context.setDefaultTimeout(20000);
    context.setDefaultNavigationTimeout(20000);
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror',error=>errors.push(error.message));
    page.on('console',msg=>{if(msg.type()==='error') errors.push(msg.text());});
    const screenshotDir = path.resolve(__dirname,'../.runtime/screenshots');
    fs.mkdirSync(screenshotDir,{recursive:true});
    await page.goto(base+'/login');
    await page.screenshot({path:path.join(screenshotDir,'login-desktop.png'),fullPage:true});
    await page.getByLabel('Địa chỉ email').fill(credentials.SEED_STUDENT_EMAIL);
    await page.getByLabel('Mật khẩu',{exact:true}).fill(credentials.SEED_STUDENT_PASSWORD);
    await page.getByRole('button',{name:'Đăng nhập',exact:true}).click();
    await page.waitForURL('**/exams');
    await page.screenshot({path:path.join(screenshotDir,'student-desktop.png'),fullPage:true});
    await page.goto(base+'/exams/1');
    await page.getByRole('button',{name:'Bắt đầu làm bài'}).click();
    await page.waitForURL(/\/attempts\/\d+$/);
    const attemptId = Number(page.url().split('/').pop());
    const [answers] = await pool.execute('SELECT id, correct_option FROM answers WHERE attempt_id = ? ORDER BY position',[attemptId]);
    for (const a of answers) await page.locator(`input[name="answers[a_${a.id}]"][value="${a.correct_option}"]`).check();
    await page.getByText('Đã lưu tất cả đáp án.',{exact:true}).waitFor();
    await page.reload();
    assert.equal(await page.locator('input[type=radio]:checked').count(),5);
    assert.notEqual(await page.locator('#countdown').textContent(),'--:--');
    await page.screenshot({path:path.join(screenshotDir,'exam-desktop.png'),fullPage:true});
    page.once('dialog',dialog=>dialog.accept());
    await page.getByRole('button',{name:'Nộp bài',exact:true}).click();
    await page.waitForURL('**/result');
    assert.equal(await page.locator('.result-score strong').textContent(),'10.00');
    await page.screenshot({path:path.join(screenshotDir,'result-desktop.png'),fullPage:true});
    await page.getByRole('button',{name:'Đăng xuất'}).click();
    await page.getByLabel('Địa chỉ email').fill(credentials.SEED_ADMIN_EMAIL);
    await page.getByLabel('Mật khẩu',{exact:true}).fill(credentials.SEED_ADMIN_PASSWORD);
    await page.getByRole('button',{name:'Đăng nhập',exact:true}).click();
    await page.waitForURL('**/admin');
    await page.screenshot({path:path.join(screenshotDir,'admin-desktop.png'),fullPage:true});
    await page.getByRole('link',{name:'+ Tạo đề thi'}).click();
    await page.getByLabel('Tên đề thi').fill('Đề thi tạo bằng trình duyệt');
    await page.getByLabel('Mô tả',{exact:true}).fill('Kiểm chứng biểu mẫu tạo đề');
    await page.getByLabel('Số lượng câu hỏi').fill('2');
    await page.locator('input[name=question_ids]').nth(0).check();
    await page.locator('input[name=question_ids]').nth(1).check();
    await page.getByLabel('Mở đề thi cho sinh viên').check();
    await page.getByRole('button',{name:'Lưu đề thi',exact:true}).click();
    await page.waitForURL('**/admin/exams');
    await page.getByText('Đề thi tạo bằng trình duyệt',{exact:true}).waitFor();
    await page.setViewportSize({width:390,height:844});
    for (const route of ['/admin','/admin/questions','/admin/exams/new','/admin/students','/admin/results']) {
      await page.goto(base+route);
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),`Tràn ngang: ${route}`);
    }
    await page.goto(base+'/admin');
    await page.getByRole('button',{name:'Mở trình đơn'}).click();
    assert.equal(await page.locator('.mobile-menu').getAttribute('aria-expanded'),'true');
    await page.getByRole('button',{name:'Đóng trình đơn'}).click();
    await page.waitForFunction(()=>document.querySelector('#sidebar').getBoundingClientRect().right <= 1);
    await page.screenshot({path:path.join(screenshotDir,'admin-mobile.png'),fullPage:true});
    await page.getByRole('button',{name:'Đăng xuất'}).click();
    await page.getByLabel('Địa chỉ email').fill(credentials.SEED_STUDENT_EMAIL);
    await page.getByLabel('Mật khẩu',{exact:true}).fill(credentials.SEED_STUDENT_PASSWORD);
    await page.getByRole('button',{name:'Đăng nhập',exact:true}).click();
    await page.waitForURL('**/exams');
    await page.screenshot({path:path.join(screenshotDir,'student-mobile.png'),fullPage:true});
    await page.goto(base+'/exams/2');
    await page.getByRole('button',{name:'Bắt đầu làm bài'}).click();
    await page.waitForURL(/\/attempts\/\d+$/);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),'Trang làm bài tràn ngang');
    await page.screenshot({path:path.join(screenshotDir,'exam-mobile.png'),fullPage:true});
    const mobileId = Number(page.url().split('/').pop());
    await page.locator('input[type=radio]').first().check();
    await page.getByText('Đã lưu tất cả đáp án.',{exact:true}).waitFor();
    await pool.execute('UPDATE attempts SET expires_at = TIMESTAMPADD(SECOND,-1,UTC_TIMESTAMP(3)) WHERE id = ?',[mobileId]);
    await page.reload();
    await page.waitForURL('**/result');
    assert.ok((await page.locator('.result-banner').textContent()).includes('Hết giờ'));
    assert.deepEqual(errors,[], 'Không có lỗi JavaScript/CSP/HTTP trên trình duyệt');
    console.log('Browser QA PASS: đăng nhập, làm bài, tự lưu, tải lại, nộp và chấm 10/10, quản trị tạo đề, responsive 390px.');
    console.log('Ảnh chụp: .runtime/screenshots. Database QA giữ lại:',database);
  } finally {
    if (browser) await browser.close();
    if (server) await new Promise(resolve=>server.close(resolve));
    await pool.end();
  }
}
main().catch(error=>{console.error(error);process.exitCode=1;});
